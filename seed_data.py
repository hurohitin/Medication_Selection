def _base_name(full_name: str) -> str:
    suffixes = [" Форте", " Плюс", " Актив", " Ретард",
                " Экспресс", " Максимум", " Про", " Ультра"]
    for suf in suffixes:
        if full_name.endswith(suf):
            return full_name[: -len(suf)]
    return full_name


def generate_drugs(per_group: int = 40):
    drugs = []
    for group, (names, substances) in GROUP_TEMPLATES.items():
        combos = []
        for name in names:
            for sub in substances:
                combos.append((name, sub))

        suffixes = ["", " Форте", " Плюс", " Актив", " Ретард",
                    " Экспресс", " Максимум", " Про", " Ультра"]
        base = list(combos)
        for name, sub in base:
            for suf in suffixes[1:]:
                combos.append((name + suf, sub))

        random.shuffle(combos)
        selected = combos[:per_group]

        base_min_age, base_max_age = GROUP_AGE_LIMITS.get(group, (0, 120))

        for name, sub in selected:
            min_age, max_age = base_min_age, base_max_age
            key = _base_name(name)
            if key in DRUG_AGE_OVERRIDES:
                min_age, max_age = DRUG_AGE_OVERRIDES[key]
            drugs.append((name, sub, group, min_age, max_age))
    return drugs


