    for did, dname, gid in all_drugs:
        for _ in range(random.randint(2, 4)):
            sid = random.choice(list(side_id.values()))
            cur.execute(
                "INSERT OR IGNORE INTO drug_side (drug_id, side_id) VALUES (?, ?)",
                (did, sid),
            )

    print("[seed] Взаимодействия...")
    cur.execute("SELECT id, group_id FROM drugs")
    by_group = {}
    for did, gid in cur.fetchall():
        by_group.setdefault(gid, []).append(did)

    seen_pairs = set()
    for gA, gB, severity, mechanism in GROUP_INTERACTIONS:
        idA = group_id.get(gA)
        idB = group_id.get(gB)
        if not idA or not idB:
            continue
        drugsA = by_group.get(idA, [])
        drugsB = by_group.get(idB, [])
        for dA in drugsA[:20]:
            for dB in drugsB[:20]:
                if dA == dB:
                    continue
                pair = tuple(sorted((dA, dB)))
                if pair in seen_pairs:
                    continue
                seen_pairs.add(pair)
                cur.execute(
                    """INSERT INTO drug_interactions
                       (drug_a_id, drug_b_id, severity, mechanism)
                       VALUES (?, ?, ?, ?)""",
                    (pair[0], pair[1], severity, mechanism),
                )

