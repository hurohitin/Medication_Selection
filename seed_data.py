SCHEMA = """
PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS drug_interactions;
DROP TABLE IF EXISTS drug_side;
DROP TABLE IF EXISTS drug_contra;
DROP TABLE IF EXISTS drug_symptoms;
DROP TABLE IF EXISTS drugs;
DROP TABLE IF EXISTS symptoms;
DROP TABLE IF EXISTS contraindications;
DROP TABLE IF EXISTS side_effects;
DROP TABLE IF EXISTS groups;

CREATE TABLE groups (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT UNIQUE NOT NULL,
    atx_code TEXT NOT NULL,
    purpose TEXT NOT NULL
);

CREATE TABLE symptoms (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT UNIQUE NOT NULL,
    location TEXT
);

CREATE TABLE contraindications (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT UNIQUE NOT NULL,
    type TEXT NOT NULL,
    risk TEXT NOT NULL
);

CREATE TABLE side_effects (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT UNIQUE NOT NULL,
    severity TEXT NOT NULL
);

CREATE TABLE drugs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    active_substance TEXT NOT NULL,
    group_id INTEGER NOT NULL,
    min_age INTEGER DEFAULT 0,
    max_age INTEGER DEFAULT 120,
    FOREIGN KEY (group_id) REFERENCES groups(id),
    UNIQUE(name, active_substance)
);

CREATE TABLE drug_symptoms (
    drug_id INTEGER NOT NULL,
    symptom_id INTEGER NOT NULL,
    PRIMARY KEY (drug_id, symptom_id),
    FOREIGN KEY (drug_id) REFERENCES drugs(id) ON DELETE CASCADE,
    FOREIGN KEY (symptom_id) REFERENCES symptoms(id) ON DELETE CASCADE
);

CREATE TABLE drug_contra (
    drug_id INTEGER NOT NULL,
    contra_id INTEGER NOT NULL,
    PRIMARY KEY (drug_id, contra_id),
    FOREIGN KEY (drug_id) REFERENCES drugs(id) ON DELETE CASCADE,
    FOREIGN KEY (contra_id) REFERENCES contraindications(id) ON DELETE CASCADE
);

CREATE TABLE drug_side (
    drug_id INTEGER NOT NULL,
    side_id INTEGER NOT NULL,
    PRIMARY KEY (drug_id, side_id),
    FOREIGN KEY (drug_id) REFERENCES drugs(id) ON DELETE CASCADE,
    FOREIGN KEY (side_id) REFERENCES side_effects(id) ON DELETE CASCADE
);

CREATE TABLE drug_interactions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    drug_a_id INTEGER NOT NULL,
    drug_b_id INTEGER NOT NULL,
    severity TEXT NOT NULL,
    mechanism TEXT NOT NULL,
    FOREIGN KEY (drug_a_id) REFERENCES drugs(id) ON DELETE CASCADE,
    FOREIGN KEY (drug_b_id) REFERENCES drugs(id) ON DELETE CASCADE
);

CREATE INDEX idx_drugs_group ON drugs(group_id);
CREATE INDEX idx_ds_symptom ON drug_symptoms(symptom_id);
CREATE INDEX idx_dc_contra ON drug_contra(contra_id);
CREATE INDEX idx_inter_a ON drug_interactions(drug_a_id);
CREATE INDEX idx_inter_b ON drug_interactions(drug_b_id);
"""


